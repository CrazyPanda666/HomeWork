#!/bin/bash
# Скрипт обратного отсчета: пользователь сам задает время.

# 1. Берем число из первого аргумента
start_num=$1

# Маленькая проверка: вдруг пользователь забыл ввести число?
if [[ -z "$start_num" ]]; then
  echo "Ошибка: укажите число секунд. Например: ./task7.sh 10"
  exit 1
fi

echo "Начинаем обратный отсчет от $start_num..."

# 2. Цикл for теперь берет числа от утилиты seq
for i in $(seq $start_num -1 1); do

  stars=""
  
  # Вложенный цикл для звездочек
  for ((j=1; j<=i; j++)); do
    stars="${stars}*"
  done

  echo -ne "\rОсталось: [$stars] $i сек"
  
  sleep 1

done

echo -e "\nВремя вышло!"
