#!/bin/bash
# Скрипт находит 10 самых частых слов в текстовом файле.

# Проверяем, что пользователь передал имя файла
if [[ -z "$1" ]]; then
  echo "Ошибка: укажите имя файла. Например: ./task3.sh text.txt"
  exit 1
fi

file=$1

# Запускаем текст через конвейер из 6 станков
cat "$file" | \
  tr '[:upper:]' '[:lower:]' | \
  tr -s ' ' '\n' | \
  sort | \
  uniq -c | \
  sort -rn | \
  head -n 10
