#!/bin/bash
# Скрипт проверяет доступность списка хостов с помощью ping.

# Задаем список хостов через пробел
hosts="google.com yandex.ru 192.168.1.1"

echo "Начинаем проверку хостов..."
echo "---------------------------"

# Запускаем цикл: для каждого хоста из списка
for host in $hosts; do
  
  # Пингуем хост. Весь технический вывод прячем в /dev/null
  if ping -c 1 -W 2 "$host" > /dev/null 2>&1; then
    echo "✅ $host - доступен"
  else
    echo "❌ $host - недоступен"
  fi
  
done

echo "---------------------------"
echo "Проверка завершена."
