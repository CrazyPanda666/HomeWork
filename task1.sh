#!/bin/bash
# Скрипт проверяет, что файл является CSV или TSV, 
# и что во всех строках одинаковое количество столбцов.

file=$1

# 1. Проверка: передан ли файл и существует ли он
if [[ -z "$file" ]] || [[ ! -f "$file" ]]; then
  echo "Ошибка: укажите существующий файл."
  exit 1
fi

# 2. Получаем расширение файла (всё после последней точки)
ext="${file##*.}"

# 3. Определяем разделитель в зависимости от расширения
if [[ "$ext" == "csv" ]]; then
  delim=","
elif [[ "$ext" == "tsv" ]]; then
  delim=$'\t'  # Специальный синтаксис bash для символа табуляции
else
  echo "Ошибка: файл должен иметь расширение .csv или .tsv"
  exit 1
fi

echo "Проверяем файл $file (формат: $ext, разделитель: '$delim')..."


# 4. Считаем количество уникальных значений числа колонок
# awk считает колонки, sort сортирует, uniq схлопывает, wc -l считает итог
unique_counts=$(awk -F"$delim" '{print NF}' "$file" | sort | uniq | wc -l)

# 5. Делаем вывод
if [[ $unique_counts -eq 1 ]]; then
  echo "✅ Файл корректен: во всех строках одинаковое количество столбцов."
else
  echo "❌ Ошибка: количество столбцов в строках отличается!"
  echo "Найдено вариантов количества столбцов: $unique_counts"
fi
