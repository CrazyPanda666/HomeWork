#!/bin/bash
# Скрипт создает резервные копии всех .txt файлов, добавляя к имени дату.

# 1. Узнаем сегодняшнюю дату и сохраняем в переменную today
today=$(date +%Y-%m-%d)

# 2. Запускаем цикл: для каждого файла, который заканчивается на .txt
for file in *.txt; do
  
  # 3. Придумываем новое имя: отрезаем .txt и приклеиваем _дата.txt
  new_name="${file%.txt}_${today}.txt"
  
  # 4. Копируем файл: cp (оригинал) (новая_копия)
  cp "$file" "$new_name"
  
  echo "Создана копия: $new_name"
  
done
