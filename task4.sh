#!/bin/bash
# Скрипт генерирует отчет о файлах в директории: размер, количество и типы.

dir=$1

# 1. Проверка: передана ли директория и существует ли она
if [[ -z "$dir" ]] || [[ ! -d "$dir" ]]; then
  echo "Ошибка: укажите существующую директорию. Например: ./task4.sh ."
  exit 1
fi

echo "=== Отчет по директории: $dir ==="

# 2. Общий размер
total_size=$(du -sh "$dir" | awk '{print $1}')
echo "Общий размер: $total_size"

# 3. Общее количество файлов
total_files=$(find "$dir" -type f | wc -l)
echo "Всего файлов: $total_files"

echo "--- Количество файлов по типам (расширениям) ---"
# 4. Конвейер для подсчета расширений
find "$dir" -type f -name "*.*" | \
  sed 's/.*\.//' | \
  sort | \
  uniq -c | \
  sort -rn
